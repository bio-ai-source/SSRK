"""PBMC 3k data for the matched protocol: loader, curated marker map, bootstrap resampling.

The matched protocol uses the processed 10x PBMC 3k AnnData distributed with besca
(``pbmc3k_processed.h5ad``: 2,504 cells x 1,719 highly variable genes, per-gene z-scored and clipped
at 10; paper Table A2). Evaluation labels are the 12 Leiden clusters stored in
``obs["leiden"]``; they are used only for evaluation (ARI/NMI), never for training.

The loader reads the file with ``anndata`` (no scanpy dependency) and returns exactly the arrays of
the original loader (``load_pbmc_data(source="processed", n_hvgs=1719, normalize=True,
zscore_clip=None)``): ``X`` float32 as stored, ``labels = obs["leiden"].cat.codes`` (int8),
``gene_names = var_names``. It fails loudly if the file is missing or has an unexpected shape.
"""
from __future__ import annotations

import warnings
from pathlib import Path
from typing import Dict, List, Sequence, Set, Tuple

import numpy as np

PBMC_FILENAME = "pbmc3k_processed.h5ad"
PBMC_SHAPE = (2504, 1719)

#: Curated lineage marker map (26 genes in seven groups, paper Table A7) used for MarkerHits /
#: CoverageScore (paper App. A.8 "Metric definitions"); 17 of the genes are in the 1,719-gene universe.
PBMC_MARKER_MAP: Dict[str, List[str]] = {
    "CD4_T": ["IL7R", "CCR7", "LTB", "MALAT1"],
    "CD8_T": ["CD3D", "CD3E", "CD8A", "CD8B"],
    "NK": ["NKG7", "GNLY", "PRF1", "GZMB", "GZMA"],
    "B": ["MS4A1", "CD79A", "CD74", "CD37"],
    "Mono": ["LYZ", "S100A8", "S100A9", "CTSS", "LGALS3"],
    "DC": ["FCER1A", "CST3"],
    "Platelet": ["PPBP", "PF4"],
}


def pbmc_path(data_dir: Path) -> Path:
    return Path(data_dir) / "pbmc" / PBMC_FILENAME


def load_pbmc(data_dir: Path) -> Tuple[np.ndarray, np.ndarray, List[str]]:
    """Load the processed PBMC 3k matrix.

    Args:
        data_dir: package data directory containing ``pbmc/pbmc3k_processed.h5ad``.

    Returns:
        ``X`` (2504, 1719) float32, ``labels`` (2504,) int8 Leiden cluster codes, ``gene_names`` (1719).
    """
    path = pbmc_path(data_dir)
    if not path.exists():
        raise FileNotFoundError(
            f"PBMC 3k processed file not found: {path}. See data/README.md for the download link and "
            "checksum (the file is not generated by this package)."
        )
    import anndata

    with warnings.catch_warnings():
        # anndata moves the legacy .uns['neighbors'] graphs to .obsp on read (FutureWarning); harmless
        warnings.simplefilter("ignore", FutureWarning)
        adata = anndata.read_h5ad(str(path))
    X = adata.X
    if hasattr(X, "toarray"):
        X = X.toarray()
    X = np.asarray(X, dtype=np.float32)
    if "leiden" not in adata.obs:
        raise KeyError(f"{path}: obs['leiden'] (evaluation labels) is missing")
    labels = adata.obs["leiden"].cat.codes.values
    gene_names = adata.var_names.tolist()
    if X.shape != PBMC_SHAPE:
        raise RuntimeError(f"PBMC protocol requires {PBMC_SHAPE}, got {X.shape}")
    return X, labels, gene_names


def pbmc_marker_indices(gene_names: Sequence[str]) -> Tuple[Dict[str, Set[int]], Set[int]]:
    """Column indices of the curated markers present in the gene universe, per group and overall."""
    name_to_idx = {str(gene): i for i, gene in enumerate(gene_names)}
    groups = {
        group: {name_to_idx[g] for g in genes if g in name_to_idx}
        for group, genes in PBMC_MARKER_MAP.items()
    }
    all_markers: Set[int] = set()
    for members in groups.values():
        all_markers.update(members)
    return groups, all_markers


def bootstrap_resample(X: np.ndarray, labels: np.ndarray, seed: int) -> Tuple[np.ndarray, np.ndarray]:
    """Row bootstrap of one matched-protocol unit: ``n`` draws with replacement, ``default_rng(seed)``."""
    rng = np.random.default_rng(seed)
    idx = rng.choice(X.shape[0], size=X.shape[0], replace=True)
    return X[idx].astype(np.float32), labels[idx]
